//! The current invocation: which function is running on this task, for whom,
//! and how deep in an observe chain.
//!
//! The SDK sets it around every handler it runs, remote (an `invokefunction`
//! from the engine) or local (a [`trigger`](crate::IIIClient::trigger) of a
//! function this worker hosts). Calls made from inside a handler read it to
//! fill `caller` and `observe_depth`, and [`Observer::emit`](crate::Observer::emit)
//! reads it to tell who caused an event.
//!
//! It lives in a [`tokio::task_local!`], so it follows the handler's future
//! across `.await` points but not into a task the handler spawns. Carry it
//! explicitly with [`scope`]:
//!
//! ```rust,no_run
//! # async fn handler() {
//! let ctx = iii_sdk::current_invocation();
//! tokio::spawn(iii_sdk::scope(ctx, async move {
//!     // calls made here still name the handler as their caller
//! }));
//! # }
//! ```

use std::{future::Future, sync::Arc};

use serde_json::Value;

use crate::protocol::{Activation, Caller};

/// The invocation a handler is running for.
#[derive(Debug, Clone, PartialEq)]
pub struct InvocationCtx {
    /// The function being invoked.
    pub function_id: String,
    /// This invocation's id (generated by the SDK for a local call).
    pub invocation_id: String,
    /// Who made the call: the engine-stamped caller of a remote invocation,
    /// or this worker (with the calling handler) for a local one. `None` when
    /// the engine did not say (an engine older than 0.25).
    pub caller: Option<Caller>,
    /// Set when this invocation is an observer activation.
    pub activation: Option<Activation>,
    /// Depth of the causal chain in observe hops; 0 outside observers.
    pub observe_depth: u32,
    /// The invocation's metadata sidecar.
    pub metadata: Option<Value>,
    /// W3C trace context of the invocation's `execute` span, when tracing is
    /// on: events emitted from it join its trace.
    pub traceparent: Option<String>,
    /// W3C baggage of the invocation.
    pub baggage: Option<String>,
}

/// The current invocation plus what the SDK tracks per task.
#[derive(Debug)]
pub(crate) struct Frame {
    /// `None` inside `scope(None, ..)`: no invocation, but the nesting stays.
    pub ctx: Option<InvocationCtx>,
    /// How many local calls are nested on this task's stack.
    pub local_depth: u32,
}

impl Frame {
    /// The invocation of a frame the SDK created for a handler.
    pub(crate) fn invocation(&self) -> &InvocationCtx {
        self.ctx
            .as_ref()
            .expect("a handler's frame always has its invocation")
    }
}

tokio::task_local! {
    static CURRENT: Option<Arc<Frame>>;
}

/// The invocation the calling task is running for, or `None` outside any
/// handler (and in a task spawned from a handler without [`scope`]).
pub fn current_invocation() -> Option<InvocationCtx> {
    with_current(|ctx| ctx.cloned())
}

/// Runs `fut` with `ctx` as its current invocation. Use it to keep the
/// handler's context in a task it spawns; `None` runs `fut` outside any
/// invocation. The local-call nesting of the calling task is carried too, so
/// recursing through spawned tasks stays bounded.
pub fn scope<F>(ctx: impl Into<Option<InvocationCtx>>, fut: F) -> impl Future<Output = F::Output>
where
    F: Future,
{
    let frame = Frame {
        ctx: ctx.into(),
        local_depth: local_depth(),
    };
    CURRENT.scope(Some(Arc::new(frame)), fut)
}

/// Borrow-based access for the SDK's hot paths: no clone of the context.
pub(crate) fn with_current<R>(f: impl FnOnce(Option<&InvocationCtx>) -> R) -> R {
    let mut f = Some(f);
    match CURRENT.try_with(|frame| {
        (f.take().expect("called once"))(frame.as_ref().and_then(|f| f.ctx.as_ref()))
    }) {
        Ok(result) => result,
        Err(_) => (f.take().expect("not called"))(None),
    }
}

/// Local calls nested on the current task's stack.
pub(crate) fn local_depth() -> u32 {
    CURRENT
        .try_with(|frame| frame.as_ref().map_or(0, |f| f.local_depth))
        .unwrap_or(0)
}

/// Runs `fut` inside an already shared frame.
pub(crate) fn scope_frame<F>(frame: Arc<Frame>, fut: F) -> impl Future<Output = F::Output>
where
    F: Future,
{
    CURRENT.scope(Some(frame), fut)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ctx(function_id: &str) -> InvocationCtx {
        InvocationCtx {
            function_id: function_id.to_string(),
            invocation_id: "inv-1".to_string(),
            caller: None,
            activation: None,
            observe_depth: 2,
            metadata: None,
            traceparent: None,
            baggage: None,
        }
    }

    #[tokio::test]
    async fn absent_outside_a_scope() {
        assert!(current_invocation().is_none());
    }

    #[tokio::test]
    async fn scope_sets_it_across_awaits() {
        scope(ctx("a::b"), async {
            tokio::task::yield_now().await;
            let current = current_invocation().unwrap();
            assert_eq!(current.function_id, "a::b");
            assert_eq!(current.observe_depth, 2);
        })
        .await;
        assert!(current_invocation().is_none());
    }

    #[tokio::test]
    async fn spawned_task_loses_it_unless_scoped() {
        scope(ctx("a::b"), async {
            let lost = tokio::spawn(async { current_invocation() }).await.unwrap();
            assert!(lost.is_none());
            let kept = tokio::spawn(scope(current_invocation(), async { current_invocation() }))
                .await
                .unwrap();
            assert_eq!(kept.unwrap().function_id, "a::b");
        })
        .await;
    }

    #[tokio::test]
    async fn scope_carries_the_local_nesting() {
        let frame = Arc::new(Frame {
            ctx: Some(ctx("a::b")),
            local_depth: 7,
        });
        scope_frame(frame, async {
            let with_ctx = tokio::spawn(scope(current_invocation(), async { local_depth() }));
            assert_eq!(with_ctx.await.unwrap(), 7);
            let without = tokio::spawn(scope(None, async {
                (local_depth(), current_invocation().is_none())
            }));
            assert_eq!(without.await.unwrap(), (7, true));
        })
        .await;
    }

    #[tokio::test]
    async fn none_scope_clears_it() {
        scope(ctx("a::b"), async {
            let inner = scope(None, async { current_invocation() }).await;
            assert!(inner.is_none());
        })
        .await;
    }
}
